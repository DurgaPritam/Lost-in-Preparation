/**
 * Generate TypeScript types and Zod schemas from the contract JSON Schemas (../contract/schemas/*.schema.json).
 * Output: lib/data/generated/<file>.ts, one module per contract file, each exporting the generated interfaces and
 * `schema` (Zod). Never edit the output by hand; it is regenerated before every build, type-check and test.
 */
import { readFile, readdir, writeFile, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import $RefParser from '@apidevtools/json-schema-ref-parser';
import { compile } from 'json-schema-to-typescript';
import { jsonSchemaToZod } from 'json-schema-to-zod';

const here = path.dirname(fileURLToPath(import.meta.url));
const SCHEMAS = path.resolve(here, '../../contract/schemas');
const OUT = path.resolve(here, '../lib/data/generated');

/** The site validates strictly: an object with fixed properties and no additionalProperties rule is closed, so an
 *  unexpected field in a site-data file fails the build instead of being silently dropped. */
function closeObjects(node, seen = new Set()) {
  if (!node || typeof node !== 'object' || seen.has(node)) return;
  seen.add(node);
  if (node.type === 'object' && node.properties) {
    if (node.additionalProperties === undefined) node.additionalProperties = false;
    // The exporters always write every field (Pydantic model_dump), so the site also requires every declared field.
    node.required = Object.keys(node.properties);
  }
  for (const v of Object.values(node)) closeObjects(v, seen);
}

const camel = (s) => s.replace(/\.schema\.json$/, '').replace(/[._-](\w)/g, (_, c) => c.toUpperCase());

await rm(OUT, { recursive: true, force: true });
await mkdir(OUT, { recursive: true });
const files = (await readdir(SCHEMAS)).filter((f) => f.endsWith('.schema.json')).sort();
const index = [];
for (const f of files) {
  const raw = JSON.parse(await readFile(path.join(SCHEMAS, f), 'utf8'));
  const name = camel(f);
  const closed = structuredClone(raw);
  closeObjects(closed);
  const ts = await compile(closed, `${name[0].toUpperCase()}${name.slice(1)}File`, {
    bannerComment: '', additionalProperties: false, strictIndexSignatures: true, unreachableDefinitions: false,
  });
  const deref = await $RefParser.dereference(structuredClone(raw));
  delete deref.$defs;
  closeObjects(deref);
  const zod = jsonSchemaToZod(deref, { module: 'none', noImport: true });
  const body = `/* eslint-disable */\n// GENERATED by scripts/gen-contract.mjs from contract/schemas/${f}. Do not edit.\nimport { z } from 'zod';\n\n${ts}\nexport const schema = ${zod};\n`;
  await writeFile(path.join(OUT, `${name}.ts`), body);
  index.push(`export * as ${name} from './${name}';`);
}
const version = JSON.parse(await readFile(path.join(SCHEMAS, files[0]), 'utf8')).$id.split('/')[2];
index.push(`export const CONTRACT_VERSION = ${JSON.stringify(version)};`);
await writeFile(path.join(OUT, 'index.ts'), `// GENERATED. Do not edit.\n${index.join('\n')}\n`);
console.log(`generated ${files.length} contract modules (contract ${version}) in lib/data/generated/`);
