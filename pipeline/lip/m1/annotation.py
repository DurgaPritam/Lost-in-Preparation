"""Build annotation/data.js (sample + enums + guidelines) for the static annotation tool.

The tool never sees model predictions, so annotators stay independent of the LLM.
"""
from __future__ import annotations

import json

from ..paths import ROOT
from .prompt import PROMPT_DIR
from .sample import SAMPLE_PATH
from .schema import ENUMS, values

OUT = ROOT / "annotation" / "data.js"


def build() -> str:
    payload = {
        "sample": json.loads(SAMPLE_PATH.read_text()),
        "enums": {k: values(v) for k, v in ENUMS.items()},
        "guidelines": (PROMPT_DIR / "guidelines.md").read_text(),
        "guidelinesVersion": "v1",
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// Generated by `python -m lip m1 sample`. Do not edit.\nwindow.LIP = "
                   + json.dumps(payload, ensure_ascii=False) + ";\n")
    return str(OUT.relative_to(ROOT))
